    private static void icon(String name, String... rows) {
        StringBuilder svg = new StringBuilder("<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 7 7\" width=\"7\" height=\"7\" "
                + "shape-rendering=\"crispEdges\" fill=\"#fff\">");
        for (int y = 0; y < rows.length; y++) {
            String row = rows[y];
            for (int x = 0; x < Math.min(7, row.length()); x++) {
                if (row.charAt(x) == '#') {
                    // Merge runs into one rect per row segment.
                    int start = x;
                    while (x + 1 < Math.min(7, row.length()) && row.charAt(x + 1) == '#') {
                        x++;
                    }
                    svg.append("<rect x=\"").append(start).append("\" y=\"").append(y).append("\" width=\"").append(x - start + 1).append("\" height=\"1\"/>");
                }
            }
        }
        svg.append("</svg>");
        PixelIcon.register(name, PixelIcon.KIT_FRAME, true, svg.toString());
    }
